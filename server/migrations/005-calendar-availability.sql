CREATE TABLE IF NOT EXISTS business_availability (
    weekday TINYINT UNSIGNED PRIMARY KEY,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    opens TIME NOT NULL DEFAULT '09:00:00',
    closes TIME NOT NULL DEFAULT '17:00:00'
) ENGINE=InnoDB;
