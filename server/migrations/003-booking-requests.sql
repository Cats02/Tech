CREATE TABLE IF NOT EXISTS customers (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    address VARCHAR(500) NOT NULL DEFAULT '',
    notes TEXT NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    UNIQUE KEY customer_contact (email, phone),
    INDEX customer_name (name)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    submission_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    customer_id BIGINT UNSIGNED NOT NULL,
    service_id BIGINT UNSIGNED NOT NULL,
    status ENUM('PENDING','CONFIRMED','COMPLETED','CANCELLED','DECLINED') NOT NULL DEFAULT 'PENDING',
    customer_name VARCHAR(160) NOT NULL,
    customer_email VARCHAR(254) NOT NULL,
    customer_phone VARCHAR(20) NOT NULL,
    service_name VARCHAR(160) NOT NULL,
    amount_cents INT UNSIGNED NULL,
    price_type VARCHAR(20) NOT NULL,
    billing_unit VARCHAR(20) NOT NULL,
    duration_minutes SMALLINT UNSIGNED NOT NULL,
    appointment_type VARCHAR(20) NOT NULL,
    address VARCHAR(500) NOT NULL DEFAULT '',
    preferred_start DATETIME(3) NOT NULL,
    alternative_start DATETIME(3) NULL,
    description TEXT NOT NULL,
    terms_version VARCHAR(40) NOT NULL,
    terms_accepted_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    confirmed_start DATETIME(3) NULL,
    confirmed_end DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    FOREIGN KEY (customer_id) REFERENCES customers(id),
    FOREIGN KEY (service_id) REFERENCES services(id),
    INDEX bookings_status_start (status, preferred_start),
    INDEX bookings_customer (customer_id, created_at),
    INDEX bookings_service (service_id)
) ENGINE=InnoDB;
